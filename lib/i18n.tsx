const tables: Record<Lang, Record<Key, string>> = { en, hi, bn };

export function translate(lang: Lang, key: Key, vars?: Record<string, string | number>): string {
  let text = tables[lang][key] ?? en[key] ?? key;
  if (vars) {
    for (const [name, value] of Object.entries(vars)) text = text.replaceAll(`{${name}}`, String(value));
  }
  return text;
}

type I18n = {
  lang: Lang;
  setLang: (lang: Lang) => void;
  t: (key: Key, vars?: Record<string, string | number>) => string;
  ago: (iso: string, now: number) => string;
};

const Ctx = createContext<I18n | null>(null);

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = useState<Lang>("en");

  useEffect(() => {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (saved === "hi" || saved === "bn" || saved === "en") setLangState(saved);
  }, []);

  useEffect(() => {
    document.documentElement.lang = lang;
  }, [lang]);

  const setLang = useCallback((next: Lang) => {
    setLangState(next);
    localStorage.setItem(STORAGE_KEY, next);
  }, []);

  const t = useCallback((key: Key, vars?: Record<string, string | number>) => translate(lang, key, vars), [lang]);

  const ago = useCallback(
    (iso: string, now: number) => {
      const m = minutesAgo(iso, now);
      if (m < 1) return t("agoNow");
      if (m < 60) return t("agoMin", { n: m });
      const h = Math.floor(m / 60);
      if (h < 24) return t("agoHr", { n: h });
      return t("agoDay", { n: Math.floor(h / 24) });
    },
    [t],
  );

  const value = useMemo(() => ({ lang, setLang, t, ago }), [lang, setLang, t, ago]);
  return <Ctx.Provider value={value}>{children}</Ctx.Provider>;
}

export function useI18n(): I18n {
  const ctx = useContext(Ctx);
  if (!ctx) throw new Error("useI18n must be used within I18nProvider");
  return ctx;
}
