"use client";

/**
 * Data access seam. Every screen goes through these functions; they talk to Supabase
 * or, in DATA_MOCK mode, to the in-memory store with the same semantics.
 */
import { IS_MOCK, LIMITS, PHOTO_BUCKET, SUPABASE_URL } from "./config";
import { AppError } from "./errors";
import { mockStore } from "./mock/store";
import { supabaseBrowser } from "./supabase/client";
import type {
  Bounds,
  Cluster,
  CrowdLevel,
  FlagReason,
  ListResult,
  NewPandal,
  PandalDetail,
  PandalSummary,
  Photo,
} from "./types";

interface RpcRow {
  id: string;
  name: string;
  address: string | null;
  city: string | null;
  tags: string[] | null;
  status: PandalSummary["status"];
  lat: number;
  lng: number;
  distance_m: number | null;
  cover_path: string | null;
  crowd_level: CrowdLevel | null;
  crowd_wait: number | null;
  crowd_at: string | null;
}

export function photoUrl(path: string): string {
  return `${SUPABASE_URL}/storage/v1/object/public/${PHOTO_BUCKET}/${path
    .split("/")
    .map(encodeURIComponent)
    .join("/")}`;
}

function toSummary(r: RpcRow, keepDistance: boolean): PandalSummary {
  return {
    id: r.id,
    name: r.name,
    address: r.address,
    city: r.city,
    lat: r.lat,
    lng: r.lng,
    tags: r.tags ?? [],
    status: r.status,
    cover_url: r.cover_path ? photoUrl(r.cover_path) : null,
    distance_m: keepDistance ? r.distance_m : null,
    crowd:
      r.crowd_level && r.crowd_at
        ? { level: r.crowd_level, wait_minutes: r.crowd_wait, created_at: r.crowd_at }
        : null,
  };
}

function truncate(rows: RpcRow[], limit: number, keepDistance: boolean): ListResult {
  return {
    items: rows.slice(0, limit).map((r) => toSummary(r, keepDistance)),
    truncated: rows.length > limit,
  };
}

export async function requireUid(): Promise<string> {
  const { data } = await supabaseBrowser().auth.getUser();
  if (!data.user) throw new AppError("NOT_SIGNED_IN");
  return data.user.id;
}

export async function nearbyPandals(lat: number, lng: number): Promise<ListResult> {
  if (IS_MOCK) return mockStore.nearby(lat, lng);
  const { data, error } = await supabaseBrowser().rpc("nearby_pandals", { p_lat: lat, p_lng: lng });
  if (error) throw error;
  return truncate(data as RpcRow[], LIMITS.nearbyLimit, true);
}

export async function pandalsInBounds(b: Bounds): Promise<ListResult> {
  if (IS_MOCK) return mockStore.inBounds(b);
  const { data, error } = await supabaseBrowser().rpc("pandals_in_bounds", {
    p_south: b.south,
    p_west: b.west,
    p_north: b.north,
    p_east: b.east,
  });
  if (error) throw error;
  return truncate(data as RpcRow[], LIMITS.boundsLimit, false);
}

export async function pandalClusters(b: Bounds, cellDeg: number): Promise<Cluster[]> {
  if (IS_MOCK) return mockStore.clusters(b, cellDeg);
  const { data, error } = await supabaseBrowser().rpc("pandal_clusters", {
    p_south: b.south,
    p_west: b.west,
    p_north: b.north,
    p_east: b.east,
    p_cell_deg: cellDeg,
  });
  if (error) throw error;
  return (data as { lat: number; lng: number; count: number | string }[]).map((c) => ({
    lat: c.lat,
    lng: c.lng,
    count: Number(c.count),
  }));
}

export async function getPandal(id: string): Promise<PandalDetail | null> {
  if (IS_MOCK) return mockStore.get(id);
  const { data, error } = await supabaseBrowser().rpc("get_pandal", { p_id: id });
  if (error) throw error;
  if (!data) return null;
  const d = data as Omit<PandalDetail, "photos" | "cover_url" | "distance_m"> & {
    photos: Omit<Photo, "url" | "pandal_id">[];
  };
  const photos: Photo[] = d.photos.map((p) => ({ ...p, pandal_id: d.id, url: photoUrl(p.storage_path) }));
  const cover = photos.find((p) => p.status === "active");
  return { ...d, tags: d.tags ?? [], photos, cover_url: cover?.url ?? null, distance_m: null };
}

export async function findDuplicates(lat: number, lng: number, name: string): Promise<PandalSummary[]> {
  if (IS_MOCK) return mockStore.duplicates(lat, lng, name);
  const { data, error } = await supabaseBrowser().rpc("find_duplicates", { p_lat: lat, p_lng: lng, p_name: name });
  if (error) throw error;
  return (data as RpcRow[]).map((r) => toSummary(r, true));
}

/**
 * Idempotent: `id` is generated by the client and saved before the request, so a retry
 * after a lost response re-sends the same id instead of creating a second pandal.
 */
export async function createPandal(input: NewPandal, uid: string, id: string): Promise<string> {
  if (IS_MOCK) return mockStore.createPandal(input, uid, id);
  const sb = supabaseBrowser();
  const { error } = await sb
    .from("pandals")
    .insert({
      id,
      name: input.name.trim(),
      description: input.description.trim() || null,
      address: input.address.trim() || null,
      city: input.city.trim() || null,
      tags: input.tags,
      location: `SRID=4326;POINT(${input.lng} ${input.lat})`,
    });
  if (error) {
    // Primary-key clash = our earlier attempt actually succeeded. Confirm it's ours.
    if (error.code === "23505") {
      const { data } = await sb.from("pandals").select("id, created_by").eq("id", id).maybeSingle();
      if (data?.created_by === uid) return id;
    }
    throw error;
  }
  return id;
}

/**
 * Idempotent: `photoId` is fixed per selected photo (persisted with it), so the object
 * path and row id are the same on every retry. An object or row that already exists from
 * an earlier attempt whose response was lost counts as success.
 */
export async function uploadPhoto(pandalId: string, file: Blob, uid: string, photoId: string): Promise<void> {
  if (IS_MOCK) return mockStore.addPhoto(pandalId, file, uid, photoId);
  const sb = supabaseBrowser();
  const ext = file.type === "image/png" ? "png" : file.type === "image/webp" ? "webp" : "jpg";
  const path = `${uid}/${pandalId}/${photoId}.${ext}`;
  const up = await sb.storage.from(PHOTO_BUCKET).upload(path, file, {
    contentType: file.type || "image/jpeg",
    cacheControl: "31536000",
    upsert: false,
  });
  const alreadyUploaded =
    up.error && (/already exists|duplicate/i.test(up.error.message) || String((up.error as { statusCode?: string }).statusCode) === "409");
  if (up.error && !alreadyUploaded) throw up.error;

  const { error } = await sb.from("photos").insert({ id: photoId, pandal_id: pandalId, storage_path: path });
  if (!error) return;
  if (error.code === "23505") {
    const { data } = await sb.from("photos").select("user_id").eq("id", photoId).maybeSingle();
    if (data?.user_id === uid) return; // earlier attempt already saved it
  }
  // Row rejected (e.g. quota): don't leave the object behind.
  await sb.storage.from(PHOTO_BUCKET).remove([path]);
  throw error;
}

export async function reportCrowd(pandalId: string, level: CrowdLevel, wait: number | null, uid: string) {
  if (IS_MOCK) return mockStore.reportCrowd(pandalId, level, wait, uid);
  const { error } = await supabaseBrowser()
    .from("crowd_reports")
    .insert({ pandal_id: pandalId, level, wait_minutes: wait });
  if (error) throw error;
}

export async function flagItem(kind: "pandal" | "photo", targetId: string, reason: FlagReason, uid: string) {
  if (IS_MOCK) return mockStore.flag(kind, targetId, reason, uid);
  const table = kind === "pandal" ? "pandal_flags" : "photo_flags";
  const { error } = await supabaseBrowser().from(table).insert({ target_id: targetId, reason });
  if (error) throw error;
}

/** Server route deletes the row as the user, then removes all its photo objects. */
export async function deletePandal(id: string, uid: string) {
  if (IS_MOCK) return mockStore.deletePandal(id, uid);
  const res = await fetch(`/api/pandals/${encodeURIComponent(id)}`, { method: "DELETE" });
  if (res.ok) return;
  const body = (await res.json().catch(() => ({}))) as { error?: string; code?: string };
  if (res.status === 401) throw new AppError("NOT_SIGNED_IN");
  if (res.status === 403) throw new AppError("PERMISSION");
  throw Object.assign(new Error(body.error ?? "Delete failed"), { code: body.code });
}

export async function deletePhoto(photo: Photo, uid: string) {
  if (IS_MOCK) return mockStore.deletePhoto(photo.id, uid);
  const sb = supabaseBrowser();
  const { error, count } = await sb.from("photos").delete({ count: "exact" }).eq("id", photo.id);
  if (error) throw error;
  if (!count) throw new AppError("PERMISSION");
  await sb.storage.from(PHOTO_BUCKET).remove([photo.storage_path]);
}

/** Calls `onChange` whenever a crowd report is added anywhere. Returns an unsubscribe fn. */
export function subscribeCrowd(onChange: () => void): () => void {
  if (IS_MOCK) {
    const off = mockStore.subscribe(onChange);
    return () => void off();
  }
  const sb = supabaseBrowser();
  const channel = sb
    .channel("crowd-reports")
    .on("postgres_changes", { event: "INSERT", schema: "public", table: "crowd_reports" }, () => onChange())
    .subscribe();
  return () => {
    void sb.removeChannel(channel);
  };
}


